# The keys the server used to store as plain Italian text in update.json.
_LEGACY_ERRORS = {
    "Controllo non riuscito: PyPI non ha risposto in tempo.": "update.timeout",
    "Controllo non riuscito: controlla la connessione e riprova.": "update.network",
}


def language() -> str:
    try:
        chosen = str(config.load_settings().get("language") or "it")
    except Exception:
        chosen = "it"
    return chosen if chosen in LANGUAGES else "it"


def t(message_key: str, **values) -> str:
    """Translate one server message into the language saved in Settings.

    The first parameter is deliberately not called ``key`` so that a caller may
    pass ``key=...`` as a placeholder value (e.g. ``t("data.missing", key=...)``).
    """
    message_key = _LEGACY_ERRORS.get(str(message_key), str(message_key))
    table = MESSAGES.get(language()) or MESSAGES["it"]
    text = table.get(message_key) or MESSAGES["it"].get(message_key) or message_key
    if not values:
        return text
    try:
        return text.format(**values)
    except (KeyError, IndexError, ValueError):
        return text
